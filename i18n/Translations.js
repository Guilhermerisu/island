// Only display strings are translated. Commands, page IDs and user data stay
// in their original form; both languages remain available to search.
var cache = Object.create(null)
var cacheSize = 0
function normalize(value) { return String(value || "").toLowerCase().replace(/ё/g, "е") }
function plural(value, one, few, many) {
  var n = Math.abs(Number(value)) % 100
  return n >= 11 && n <= 14 ? many : n % 10 === 1 ? one : n % 10 >= 2 && n % 10 <= 4 ? few : many
}
function translate(source, language, depth) {
  var text = source === null || source === undefined ? "" : String(source)
  if (language !== "ru" || !/[A-Za-z]/.test(text)) return text
  if (Object.prototype.hasOwnProperty.call(ru, text)) return ru[text]
  if (Object.prototype.hasOwnProperty.call(cache, text)) return cache[text]
  var result = text
  var trimmed = text.trim()
  if (Object.prototype.hasOwnProperty.call(ru, trimmed)) {
    result = text.slice(0, text.indexOf(trimmed)) + ru[trimmed] + text.slice(text.indexOf(trimmed) + trimmed.length)
  } else if ((depth || 0) < 4) {
    // Icons and punctuation can precede a translated label.
    var icon = text.match(/^([^A-Za-z0-9]+)([A-Za-z][\s\S]*)$/)
    var parts = text.split(/( › | · | \/ )/)
    var count = text.match(/^(\d+) (seconds?|minutes?|hours?|days?|files?|packages?|processes|notifications?|columns?|active)$/)
    if (icon && Object.prototype.hasOwnProperty.call(ru, icon[2])) result = icon[1] + ru[icon[2]]
    else if (text.indexOf("Search or ") === 0) result = "Поиск или " + translate(text.slice(10), language, (depth || 0) + 1)
    else if (parts.length > 1) result = parts.map(function(part) { return translate(part, language, (depth || 0) + 1) }).join("")
    else if (count) {
      var forms = {
        second: ["секунда","секунды","секунд"], minute: ["минута","минуты","минут"], hour: ["час","часа","часов"],
        day: ["день","дня","дней"], file: ["файл","файла","файлов"], package: ["пакет","пакета","пакетов"],
        processe: ["процесс","процесса","процессов"], notification: ["уведомление","уведомления","уведомлений"],
        column: ["колонка","колонки","колонок"], active: ["активное","активных","активных"]
      }
      var form = forms[count[2].replace(/s$/, "")]
      if (form) result = count[1] + " " + plural(count[1], form[0], form[1], form[2])
    } else {
      var prefixes = {
        "Add ": "Добавить ", "Open ": "Открыть ", "Show ": "Показать ", "Ask ": "Спросить ",
        "Pin ": "Закрепить ", "Unpin ": "Открепить ", "Drag to Add ": "Перетащить для добавления: ",
        "Opens the ": "Открывает ", "Connected on ": "Подключено: ", "Connected · ": "Подключено · ",
        "Password for ": "Пароль для ", "Resets in ": "Сброс через ", "Reverting in ": "Отмена через ",
        "Updated ": "Обновлено ", "Today is ": "Сегодня: ", "In ": "Через ", "in ": "через ",
        "Looks like ": "Похоже на ", "Couldn't find “": "Не найдено: «", "Are you sure you want to quit “": "Завершить «"
      }
      for (var prefix in prefixes) {
        if (text.indexOf(prefix) === 0) {
          result = prefixes[prefix] + translate(text.slice(prefix.length), language, (depth || 0) + 1)
          break
        }
      }
      if (result === text) {
        var monthYear = text.match(/^([A-Za-z]+) (\d{4})$/)
        if (monthYear && ru[monthYear[1]]) result = ru[monthYear[1]] + " " + monthYear[2]
        else if (/^\d+ min ago$/.test(text)) result = text.replace("min ago", "мин назад")
        else if (/^\d+ [mh] ago$/.test(text)) result = text.replace("m ago", "мин назад").replace("h ago", "ч назад")
        else if (/^\d+h(?: \d+m)?$/.test(text)) result = text.replace("h", " ч").replace("m", " мин")
        else if (/^\d+m$/.test(text)) result = text.replace("m", " мин")
        else if (text === "Updated just now") result = "Обновлено только что"
        else if (text === "Resets now") result = "Сброс сейчас"
      }
    }
  }
  if (cacheSize > 1500) { cache = Object.create(null); cacheSize = 0 }
  cache[text] = result
  cacheSize++
  return result
}
function applicationAliases(entry) {
  var name = String(entry.name || "")
  var generic = String(entry.genericName || "")
  var result = [translate(name, "ru"), translate(generic, "ru")]
  var id = (String(entry.id || "") + " " + name).toLowerCase()
  var aliases = [
    [/firefox|librewolf|zen browser/, "браузер интернет файрфокс фаерфокс мозилла"],
    [/chrome|chromium|brave/, "браузер интернет хром хромиум браве"],
    [/telegram/, "телеграм сообщения мессенджер"], [/discord/, "дискорд звонки чат"],
    [/obsidian/, "обсидиан заметки"], [/codex/, "кодекс программирование"],
    [/kitty|ghostty|alacritty|terminal|org\.codeberg\.dnkl\.foot/, "терминал консоль"],
    [/nautilus|thunar|dolphin|file.?manager/, "файлы папки проводник файловый менеджер"],
    [/calculator|qalculate/, "калькулятор вычисления"], [/calendar/, "календарь события"],
    [/code|neovim|zed|sublime/, "редактор код программирование"], [/spotify|music|rhythmbox/, "музыка плеер спотифай"]
  ]
  for (var i = 0; i < aliases.length; i++) if (aliases[i][0].test(id)) result.push(aliases[i][1])
  return result
}
function appEntry(entry) {
  var keywords = []
  if (entry.keywords) for (var i = 0; i < entry.keywords.length; i++) keywords.push(String(entry.keywords[i]))
  return { id: entry.id, name: entry.name, genericName: entry.genericName, comment: entry.comment,
    icon: entry.icon, noDisplay: entry.noDisplay, keywords: keywords.concat(applicationAliases(entry).map(normalize)) }
}
function menuEntry(entry) {
  var aliases = (entry.aliases || []).slice()
  aliases.push(normalize(translate(entry.label, "ru")), normalize(translate(entry.description, "ru")))
  for (var i = 0; i < (entry.aliases || []).length; i++) aliases.push(translate(entry.aliases[i], "ru"))
  return Object.assign({}, entry, {aliases: aliases})
}
